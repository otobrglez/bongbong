"""Write `src/ground_mask.rs`: what every road and water tile is made of,
pixel by pixel, so the code can ask whether a point of the floor is open
water, a bank, a road's dirt or plain ground without looking at colours.

`src/ground.rs` lays roads and water through four autotile tables
(`ROAD_EDGE`, `WATER_CHANNEL`, `WATER_SHORE`, `WATER_MOUTH`) and the tiles
`tools/water_tiles.py` composes (`WATER_EXTRA`, ids 602 to 615). A tile's
shape is the same in every frame of its animation and under every theme,
so one mask per tile id - frame 0, read from the live grass tileset -
serves all of them. Each source pixel is one of:

- `water`: `water_tiles.is_water`, the test the composer itself uses;
- `bank`: any other pixel of a water tile that is not a grass-fill colour -
  the dark outline and the sandy specks along a shore;
- `road`: a warm pixel of a road tile (red at least green), the dirt;
- `land`: everything else, the grass and the road's grass-edge dither.

A source pixel is 2 x 2 field pixels (a 16 px tile drawn on a 32 px
cell), the game's 2 px block. The table is generated, never edited; run

    nix-shell -p "python3.withPackages (ps: [ps.pillow])" --run "python3 tools/ground_mask.py"

after any change to the tile tables or to `tools/water_tiles.py`. The
`ground` tests fail when a table names a tile the mask does not have.
"""

import os
import re
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import water_tiles  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, "static/punyworld/punyworld-overworld-tileset.png")
GROUND_RS = os.path.join(ROOT, "src/ground.rs")
OUT = os.path.join(ROOT, "src/ground_mask.rs")
COLS = water_tiles.COLS
T = water_tiles.T

LAND, BANK, WATER, ROAD = 0, 1, 2, 3


def table(src, name):
    """The integers of the Rust table `name` in `src`, one per entry."""
    m = re.search(r"const " + name + r": [^=]+= \[(.*?)\n\];", src, re.S)
    if not m:
        sys.exit(f"ground_mask: no table {name} in src/ground.rs")
    body = m.group(1)
    if name == "WATER_MOUTH":
        return [int(v) for v in re.findall(r"\(0b[01]+, 0b[01]+, (\d+)\)", body)]
    return [int(v) for v in re.findall(r"^\s*(\d+),", body, re.M)]


def tile_ids():
    src = open(GROUND_RS).read()
    roads = set(table(src, "ROAD_EDGE"))
    waters = set(table(src, "WATER_CHANNEL")) | set(table(src, "WATER_SHORE")) | set(table(src, "WATER_MOUTH"))
    m = re.search(r"const WATER_EXTRA: i32 = (\d+);", src)
    n = re.search(r"const WATER_EXTRA_COUNT: i32 = (\d+);", src)
    extra = int(m.group(1))
    waters |= set(range(extra, extra + int(n.group(1))))
    return sorted(roads), sorted(waters - roads)


def main():
    img = Image.open(SHEET).convert("RGBA")
    px = img.load()

    def pixels(tid):
        tx, ty = (tid % COLS) * T, (tid // COLS) * T
        return [[px[tx + x, ty + y] for x in range(T)] for y in range(T)]

    grass = {p[:3] for tid in water_tiles.GRASS_FILL for row in pixels(tid) for p in row if p[3] > 0}
    roads, waters = tile_ids()
    masks = []
    for tid in roads:
        rows = []
        for row in pixels(tid):
            rows.append([ROAD if p[3] > 0 and p[0] >= p[1] else LAND for p in row])
        masks.append((tid, rows))
    for tid in waters:
        rows = []
        for row in pixels(tid):
            out = []
            for p in row:
                if water_tiles.is_water(p):
                    out.append(WATER)
                elif p[3] > 0 and p[:3] not in grass:
                    out.append(BANK)
                else:
                    out.append(LAND)
            rows.append(out)
        masks.append((tid, rows))
    masks.sort()

    lines = [
        "//! What every road and water tile is made of, pixel by pixel: a mask per",
        "//! tile id. Generated by `tools/ground_mask.py` from the live grass",
        "//! tileset - never edit it by hand; run the script after a change to the",
        "//! ground's tile tables. Read through `ground::GroundGrid::floor_px`.",
        "",
        "/// Each entry is a tile id and its 16 rows, top first; a row packs its",
        "/// 16 source pixels two bits each, the leftmost in the lowest bits: 0",
        "/// land, 1 bank, 2 water, 3 road. Sorted by tile id.",
        f"pub(crate) const TILE_MASKS: [(i32, [u32; 16]); {len(masks)}] = [",
    ]
    for tid, rows in masks:
        packed = []
        for row in rows:
            v = 0
            for x, cls in enumerate(row):
                v |= cls << (2 * x)
            packed.append(f"0x{v:08X}")
        lines.append(f"    ({tid}, [{', '.join(packed)}]),")
    lines.append("];")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"ground_mask: {len(roads)} road and {len(waters)} water tiles -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
