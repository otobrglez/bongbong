"""Resurrect 64 -- shared pixel-art palette for every bongbong sprite sheet.

https://lospec.com/palette-list/resurrect-64

64 fixed RGB triples, in the order Lospec lists them (a near-black "outline"
tone first, then a neutral/purple-grey ramp, then hue families: red, orange,
yellow, green, teal/mint, blue, purple, pink/crimson). Every generator in
tools/ and tools/spritegen/ imports this module so all five sprite sheets
(tanks, shells, walls, damage, tracks) draw from one shared 64-color set
instead of each having their own ad-hoc literal colours -- that's the whole
point of "aligned with Resurrect 64": no stray off-palette pixel anywhere in
the generated art.

No image-library dependency here (plain tuples + a distance function), so
this is safe to import from tools/gen_damage.py (the hand-rolled PNG writer,
no Pillow) as well as the Pillow-based tools/spritegen/gen_*.py scripts.
"""

