# A few named anchors used pervasively enough (outlines, gunmetal, dark earth)
# to deserve a name instead of a magic index.
BLACK = RESURRECT64[0]    # 2e222f -- the palette's darkest tone; R64 has no
                           # true black, this is the nearest thing to it and
                           # is what OUTLINE/CHAR/dark-earth colours snap to.
GREY_DK = RESURRECT64[1]  # 3e3546
GREY_MD = RESURRECT64[2]  # 625565
GREY_LT = RESURRECT64[6]  # 7f708a
GREY_PALE = RESURRECT64[7]  # 9babb2

_cache = {}


def nearest(rgb):
    """Nearest RESURRECT64 colour to an arbitrary (r, g, b[, a]) tuple, by
    squared Euclidean RGB distance. Alpha (if present) passes through
    unchanged -- the palette has no opinion on transparency, only colour."""
    key = (rgb[0], rgb[1], rgb[2])
    hit = _cache.get(key)
    if hit is not None:
        return hit
    best, best_d = RESURRECT64[0], None
    for cand in RESURRECT64:
        d = (cand[0] - key[0]) ** 2 + (cand[1] - key[1]) ** 2 + (cand[2] - key[2]) ** 2
        if best_d is None or d < best_d:
            best, best_d = cand, d
    _cache[key] = best
    return best


def snap(rgba):
    """Snap a colour to its nearest RESURRECT64 match, preserving alpha (or
    defaulting to opaque for a bare 3-tuple)."""
    r, g, b = nearest(rgba)
    a = rgba[3] if len(rgba) > 3 else 255
    return (r, g, b, a)
